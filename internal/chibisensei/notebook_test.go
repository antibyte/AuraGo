package chibisensei

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"strings"
	"testing"
)

func TestBuildNotebookShape(t *testing.T) {
	job, err := goldenJob(t, mustCatalog(t), goldenCases[1], goldenLock).JSON()
	if err != nil {
		t.Fatal(err)
	}
	stub := []byte("print(\"chibi stub\")\n")
	nb, err := BuildNotebook(goldenRunID, job, stub)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasSuffix(nb, []byte("}\n")) {
		t.Error("notebook must end with a closing brace and a newline")
	}
	var top map[string]json.RawMessage
	if err := json.Unmarshal(nb, &top); err != nil || len(top) != 4 {
		t.Fatalf("top-level keys: %v %v", err, top)
	}
	for _, k := range []string{"cells", "metadata", "nbformat", "nbformat_minor"} {
		if _, ok := top[k]; !ok {
			t.Errorf("missing key %s", k)
		}
	}
	var doc struct {
		Cells []struct {
			CellType string   `json:"cell_type"`
			Source   []string `json:"source"`
		} `json:"cells"`
		NBFormat      int `json:"nbformat"`
		NBFormatMinor int `json:"nbformat_minor"`
	}
	if err := json.Unmarshal(nb, &doc); err != nil {
		t.Fatal(err)
	}
	if doc.NBFormat != 4 || doc.NBFormatMinor != 4 || len(doc.Cells) != 2 {
		t.Fatalf("document: %+v", doc)
	}
	if doc.Cells[0].CellType != "markdown" || strings.Join(doc.Cells[0].Source, "") != "Generated by AuraGo Chibi Sensei for run 0123abcd4567. Do not edit." {
		t.Errorf("cell 0: %+v", doc.Cells[0])
	}
	if doc.Cells[1].CellType != "code" ||
		!strings.Contains(string(nb), `"execution_count": null`) || !strings.Contains(string(nb), `"outputs": []`) {
		t.Error("cell 1 must be a code cell with execution_count null and outputs []")
	}
	code := strings.Join(doc.Cells[1].Source, "")
	for _, want := range []string{
		`proc = subprocess.Popen([sys.executable, "-u", script_path, "--job", job_path, "--out", OUT],`,
		`stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")`,
		`print(line, end="", flush=True)`,
		"rc = proc.wait()",
		`except BaseException as exc:`,
		`print("@@chibi " + json.dumps({"v": 1, "t": "exit", "code": rc}`,
	} {
		if !strings.Contains(code, want) {
			t.Errorf("code cell lacks %q", want)
		}
	}
	m := b64Assign.FindAllStringSubmatch(code, -1)
	if len(m) != 2 {
		t.Fatalf("base64 literals: %d", len(m))
	}
	for _, e := range m {
		got, err := base64.StdEncoding.DecodeString(e[2])
		want := job
		if e[1] == "SCRIPT_B64" {
			want = stub
		}
		if err != nil || !bytes.Equal(got, want) {
			t.Errorf("%s does not decode to its input", e[1])
		}
	}
}

func TestBuildNotebookRejects(t *testing.T) {
	if _, err := BuildNotebook("x", []byte("{}"), []byte("a")); err == nil {
		t.Error("invalid run id accepted")
	}
	if _, err := BuildNotebook(goldenRunID, []byte(`{"v":`), []byte("a")); err == nil {
		t.Error("invalid job accepted")
	}
	if _, err := BuildNotebook(goldenRunID, []byte("{}"), nil); err == nil {
		t.Error("empty script accepted")
	}
}
