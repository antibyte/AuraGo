package cydcreator

import (
	"fmt"
	"strings"
)

// cString quotes s as a C/C++ string literal for generated sources (plan 1b
// "board_config.h contract" rules): `"` -> \", `\` -> \\, newline -> \n,
// every other byte below 0x20 and DEL -> three-digit octal (\ooo never
// swallows a following digit), and the second `?` of "??" -> \? so no
// trigraph can form. Non-ASCII text stays raw UTF-8 (the toolchain reads
// sources as UTF-8; LVGL renders UTF-8). Layout text is valid UTF-8 because
// it comes from JSON.
//
// It is deliberately the same escaper as cStringLiteral (template.go), which
// renders the device strings header of plan 1b: one implementation, so the
// generated ui sources and the template header can never escape differently
// (TestCStringMatchesTemplateEscaper pins it). Invalid UTF-8, which layout
// text cannot contain, comes out as U+FFFD.
func cString(s string) string { return cStringLiteral(s) }

// cComment makes free text safe for the end of a // comment: control
// characters become spaces, "??" is split so no trigraph can form, and
// trailing spaces and backslashes are removed (a trailing backslash would
// continue the comment onto the next line).
func cComment(s string) string {
	var b strings.Builder
	for _, r := range s {
		// U+2028 and U+2029 are line separators for some tools.
		if r < 0x20 || r == 0x7F || r == ' ' || r == ' ' {
			r = ' '
		}
		b.WriteRune(r)
	}
	out := b.String()
	for strings.Contains(out, "??") {
		out = strings.ReplaceAll(out, "??", "? ?")
	}
	return strings.TrimRight(out, " \\")
}

// cHexColor turns "#rrggbb" into the LVGL constant lv_color_hex(0xRRGGBB).
func cHexColor(color string) string {
	return "lv_color_hex(0x" + strings.ToUpper(strings.TrimPrefix(color, "#")) + ")"
}

// cBool renders a Go bool as the C macro value 1 or 0.
func cBool(v bool) string {
	if v {
		return "1"
	}
	return "0"
}

// genHeader is the first line of every generated source below src/generated.
func genHeader(file string) string {
	return fmt.Sprintf("// src/generated/%s - generated by CYD Creator (template %s) from cyd.project.json. Do not edit.\n",
		file, TemplateVersion)
}

// codeWriter collects generated C++ with two-space indentation per level.
type codeWriter struct {
	b strings.Builder
}

// line writes one line at the given indentation level; an empty format
// writes an empty line.
func (w *codeWriter) line(indent int, format string, args ...any) {
	if format == "" {
		w.b.WriteByte('\n')
		return
	}
	w.b.WriteString(strings.Repeat("  ", indent))
	if len(args) == 0 {
		w.b.WriteString(format)
	} else {
		fmt.Fprintf(&w.b, format, args...)
	}
	w.b.WriteByte('\n')
}

// raw appends text verbatim.
func (w *codeWriter) raw(s string) { w.b.WriteString(s) }

func (w *codeWriter) String() string { return w.b.String() }
