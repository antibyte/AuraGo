package cydcreator

import (
	"fmt"
	"strings"
)

// Partition is one row of the ESP-IDF partition table.
type Partition struct {
	Name    string `json:"name"`
	Type    string `json:"type"`    // app | data
	SubType string `json:"subtype"` // ota_0 ota_1 nvs ota 0x41 spiffs
	Offset  int    `json:"offset"`
	Size    int    `json:"size"`
}

// partitionTables are the exact layouts of spec §8: always two OTA slots, the
// 4 KiB cydcc config partition (data subtype 0x41) and a LittleFS data
// partition labelled "littlefs" (subtype spiffs, which LittleFS uses on ESP32).
var partitionTables = map[int][]Partition{
	4: {
		{"nvs", "data", "nvs", 0x9000, 0x5000},
		{"otadata", "data", "ota", 0xE000, 0x2000},
		{"app0", "app", "ota_0", 0x10000, 0x1E0000},
		{"app1", "app", "ota_1", 0x1F0000, 0x1E0000},
		{"cydcc", "data", "0x41", 0x3D0000, 0x1000},
		{"littlefs", "data", "spiffs", 0x3D1000, 0x2F000},
	},
	8: {
		{"nvs", "data", "nvs", 0x9000, 0x5000},
		{"otadata", "data", "ota", 0xE000, 0x2000},
		{"app0", "app", "ota_0", 0x10000, 0x300000},
		{"app1", "app", "ota_1", 0x310000, 0x300000},
		{"cydcc", "data", "0x41", 0x610000, 0x1000},
		{"littlefs", "data", "spiffs", 0x611000, 0x1EF000},
	},
	16: {
		{"nvs", "data", "nvs", 0x9000, 0x5000},
		{"otadata", "data", "ota", 0xE000, 0x2000},
		{"app0", "app", "ota_0", 0x10000, 0x640000},
		{"app1", "app", "ota_1", 0x650000, 0x640000},
		{"cydcc", "data", "0x41", 0xC90000, 0x1000},
		{"littlefs", "data", "spiffs", 0xC91000, 0x36F000},
	},
}

// PartitionTable returns a copy of the partition table for a flash size of 4, 8
// or 16 MB. Other sizes return *Error CYD_BAD_REQUEST.
func PartitionTable(flashMB int) ([]Partition, error) {
	table, ok := partitionTables[flashMB]
	if !ok {
		return nil, NewError(CodeBadRequest,
			fmt.Sprintf("unsupported flash size %d MB (want 4, 8 or 16)", flashMB),
			map[string]any{"flash_mb": flashMB})
	}
	return append([]Partition(nil), table...), nil
}

// PartitionCSV renders the table in ESP-IDF partition-table CSV format
// (Name, Type, SubType, Offset, Size, Flags) with uppercase hex numbers.
func PartitionCSV(flashMB int) (string, error) {
	table, err := PartitionTable(flashMB)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# ESP-IDF partition table, %d MB flash. Generated by AuraGo CYD Creator, do not edit.\n", flashMB)
	b.WriteString("# Name,   Type, SubType, Offset,   Size,     Flags\n")
	for _, p := range table {
		fmt.Fprintf(&b, "%-10s%-6s%-9s%-10s%-10s\n",
			p.Name+",", p.Type+",", p.SubType+",",
			fmt.Sprintf("0x%X,", p.Offset), fmt.Sprintf("0x%X,", p.Size))
	}
	return b.String(), nil
}

// ConfigPartitionOffset returns the cydcc offset (0x3D0000 / 0x610000 / 0xC90000).
func ConfigPartitionOffset(flashMB int) (int, error) {
	return partitionField(flashMB, "cydcc", func(p Partition) int { return p.Offset })
}

// AppSlotSize returns the size of one OTA app slot.
func AppSlotSize(flashMB int) (int, error) {
	return partitionField(flashMB, "app0", func(p Partition) int { return p.Size })
}

func partitionField(flashMB int, name string, get func(Partition) int) (int, error) {
	table, err := PartitionTable(flashMB)
	if err != nil {
		return 0, err
	}
	for _, p := range table {
		if p.Name == name {
			return get(p), nil
		}
	}
	return 0, fmt.Errorf("partition %q missing from %d MB table", name, flashMB)
}
