func TestPartitionCSVParsesBack(t *testing.T) {
	for _, flash := range []int{4, 8, 16} {
		csv, _ := PartitionCSV(flash)
		table, _ := PartitionTable(flash)
		var rows [][]string
		for _, line := range strings.Split(strings.TrimRight(csv, "\n"), "\n") {
			if strings.HasPrefix(line, "#") {
				continue
			}
			fields := strings.Split(line, ",")
			if len(fields) != 6 {
				t.Fatalf("%d MB line %q has %d fields, want 6", flash, line, len(fields))
			}
			for i := range fields {
				fields[i] = strings.TrimSpace(fields[i])
			}
			rows = append(rows, fields)
		}
		if len(rows) != len(table) {
			t.Fatalf("%d MB: %d CSV rows, want %d", flash, len(rows), len(table))
		}
		for i, p := range table {
			off, _ := strconv.ParseInt(rows[i][3], 0, 64)
			size, _ := strconv.ParseInt(rows[i][4], 0, 64)
			if rows[i][0] != p.Name || rows[i][1] != p.Type || rows[i][2] != p.SubType ||
				int(off) != p.Offset || int(size) != p.Size || rows[i][5] != "" {
				t.Errorf("%d MB row %d = %v, want %+v", flash, i, rows[i], p)
			}
		}
	}
}

func TestConfigOffsetAndSlotSize(t *testing.T) {
	cases := []struct{ flash, cfg, slot int }{
		{4, 0x3D0000, 0x1E0000},
		{8, 0x610000, 0x300000},
		{16, 0xC90000, 0x640000},
	}
	for _, tc := range cases {
		cfg, err := ConfigPartitionOffset(tc.flash)
		if err != nil || cfg != tc.cfg {
			t.Errorf("ConfigPartitionOffset(%d) = 0x%X, %v; want 0x%X", tc.flash, cfg, err, tc.cfg)
		}
		slot, err := AppSlotSize(tc.flash)
		if err != nil || slot != tc.slot {
			t.Errorf("AppSlotSize(%d) = 0x%X, %v; want 0x%X", tc.flash, slot, err, tc.slot)
		}
	}
	// The overview's POST /devices example says 4001792 (0x3D1000, the littlefs
	// offset); spec §8 and the ConfigPartitionOffset contract say 0x3D0000.
	if off, _ := ConfigPartitionOffset(4); off != 3997696 {
		t.Fatalf("4 MB config offset %d, want 3997696 (0x3D0000)", off)
	}
	if _, err := ConfigPartitionOffset(3); ErrorCode(err) != CodeBadRequest {
		t.Fatalf("ConfigPartitionOffset(3) err = %v", err)
	}
}
