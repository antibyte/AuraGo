func TestPartitionTablesMatchSpec(t *testing.T) {
	type row struct {
		name, typ, sub string
		off, size      int
	}
	want := map[int][]row{
		4: {
			{"nvs", "data", "nvs", 0x9000, 0x5000},
			{"otadata", "data", "ota", 0xE000, 0x2000},
			{"app0", "app", "ota_0", 0x10000, 0x1E0000},
			{"app1", "app", "ota_1", 0x1F0000, 0x1E0000},
			{"cydcc", "data", "0x41", 0x3D0000, 0x1000},
			{"littlefs", "data", "spiffs", 0x3D1000, 0x2F000},
		},
		8: {
			{"nvs", "data", "nvs", 0x9000, 0x5000},
			{"otadata", "data", "ota", 0xE000, 0x2000},
			{"app0", "app", "ota_0", 0x10000, 0x300000},
			{"app1", "app", "ota_1", 0x310000, 0x300000},
			{"cydcc", "data", "0x41", 0x610000, 0x1000},
			{"littlefs", "data", "spiffs", 0x611000, 0x1EF000},
		},
		16: {
			{"nvs", "data", "nvs", 0x9000, 0x5000},
			{"otadata", "data", "ota", 0xE000, 0x2000},
			{"app0", "app", "ota_0", 0x10000, 0x640000},
			{"app1", "app", "ota_1", 0x650000, 0x640000},
			{"cydcc", "data", "0x41", 0xC90000, 0x1000},
			{"littlefs", "data", "spiffs", 0xC91000, 0x36F000},
		},
	}
	for flash, rows := range want {
		got, err := PartitionTable(flash)
		if err != nil {
			t.Fatalf("PartitionTable(%d): %v", flash, err)
		}
		if len(got) != len(rows) {
			t.Fatalf("%d MB: %d rows, want %d", flash, len(got), len(rows))
		}
		for i, r := range rows {
			g := got[i]
			if g.Name != r.name || g.Type != r.typ || g.SubType != r.sub || g.Offset != r.off || g.Size != r.size {
				t.Errorf("%d MB row %d = %+v, want %+v", flash, i, g, r)
			}
		}
	}
}

func TestPartitionTableInvariants(t *testing.T) {
	for _, flash := range []int{4, 8, 16} {
		table, _ := PartitionTable(flash)
		end := 0x9000 // the partition table itself lives at 0x8000..0x9000
		for _, p := range table {
			if p.Offset != end {
				t.Errorf("%d MB %s starts at 0x%X, want contiguous 0x%X", flash, p.Name, p.Offset, end)
			}
			if p.Offset%0x1000 != 0 || p.Size%0x1000 != 0 {
				t.Errorf("%d MB %s not 4 KiB aligned", flash, p.Name)
			}
			if p.Type == "app" && p.Offset%0x10000 != 0 {
				t.Errorf("%d MB %s app offset 0x%X not 64 KiB aligned", flash, p.Name, p.Offset)
			}
			end = p.Offset + p.Size
		}
		if end != flash<<20 {
			t.Errorf("%d MB table ends at 0x%X, want 0x%X", flash, end, flash<<20)
		}
		if table[2].Size != table[3].Size {
			t.Errorf("%d MB OTA slots differ", flash)
		}
	}
}

func TestPartitionTableRejectsUnknownSize(t *testing.T) {
	for _, flash := range []int{0, 2, 32} {
		if _, err := PartitionTable(flash); ErrorCode(err) != CodeBadRequest {
			t.Errorf("PartitionTable(%d) err = %v, want CYD_BAD_REQUEST", flash, err)
		}
		if _, err := PartitionCSV(flash); err == nil {
			t.Errorf("PartitionCSV(%d) accepted", flash)
		}
	}
}

func TestPartitionTableReturnsCopy(t *testing.T) {
	a, _ := PartitionTable(4)
	a[0].Name = "mutated"
	b, _ := PartitionTable(4)
	if b[0].Name != "nvs" {
		t.Fatal("PartitionTable must return a copy")
	}
}

