// Fixed parts of the generated PlatformIO project (plan 1b "platformio.ini
// contract"); the builder image pre-installs exactly these versions.
const genPlatform = "espressif32@6.13.0"

var (
	genTemplateLibDeps = []string{
		"lvgl/lvgl@9.5.0",
		"lovyan03/LovyanGFX@1.2.30",
		"tzapu/WiFiManager@2.0.17",
		"bblanchon/ArduinoJson@7.4.3",
	}
	genBuildFlags = []string{
		"-DLV_CONF_INCLUDE_SIMPLE",
		"-Iinclude",
		"-Ilib/cyd_template/config",
		"-Isrc/generated",
		`-DWM_STRINGS_FILE=\"cyd_wm_strings.h\"`,
		"-DWM_NODEBUG",
	}
	// Pin and timing keys of board_config.h, in contract order.
	genLCDPins   = []string{"BL", "RST", "SCLK", "MOSI", "MISO", "CS", "DC", "D0", "D1", "D2", "D3", "DE", "VSYNC", "HSYNC", "PCLK", "DISP", "R0", "R1", "R2", "R3", "R4", "G0", "G1", "G2", "G3", "G4", "G5", "B0", "B1", "B2", "B3", "B4"}
	genRGBTiming = []string{"PCLK_HZ", "HSYNC_POLARITY", "HSYNC_FRONT_PORCH", "HSYNC_PULSE_WIDTH", "HSYNC_BACK_PORCH", "VSYNC_POLARITY", "VSYNC_FRONT_PORCH", "VSYNC_PULSE_WIDTH", "VSYNC_BACK_PORCH", "PCLK_ACTIVE_NEG"}
	genTouchPins = []string{"SCLK", "MOSI", "MISO", "CS", "IRQ", "SDA", "SCL", "INT", "RST"}
	genWiFiModes = map[string]int{"off": 0, "optional": 1, "required": 2}
)

// genRotation maps the project orientation to the template's CYD_ROTATION,
// relative to the board's native orientation.
func genRotation(native, orientation string) int {
	order := []string{"landscape", "portrait", "landscape_flipped", "portrait_flipped"}
	if native == "portrait" {
		order = []string{"portrait", "landscape", "portrait_flipped", "landscape_flipped"}
	}
	if i := slices.Index(order, orientation); i >= 0 {
		return i
	}
	return 0
}

func pinOr(pins map[string]int, key string) int {
	if v, ok := pins[strings.ToLower(key)]; ok {
		return v
	}
	return -1
}

// renderBoardConfig writes include/board_config.h: every macro of the plan 1b
// contract, always, in contract order.
func renderBoardConfig(p Project, b Board, projectID string) string {
	var w codeWriter
	def := func(name string, value any) { w.line(0, "#define %s %v", name, value) }
	w.line(0, "// include/board_config.h - generated by CYD Creator (template %s) for board %s. Do not edit.", TemplateVersion, b.ID)
	w.line(0, "#pragma once")
	w.line(0, "")
	w.line(0, "// Board")
	def("CYD_BOARD_ID", cString(b.ID))
	def("CYD_CHIP_"+strings.ToUpper(b.Chip), 1)
	def("CYD_FLASH_MB", b.FlashMB)
	def("CYD_HAS_PSRAM", cBool(b.PSRAM))
	w.line(0, "")
	w.line(0, "// Display")
	d := b.Display
	def("CYD_PANEL_DRIVER_"+d.Driver, 1)
	def("CYD_PANEL_BUS_"+strings.ToUpper(d.Bus), 1)
	def("CYD_PANEL_NATIVE_W", d.Width)
	def("CYD_PANEL_NATIVE_H", d.Height)
	def("CYD_PANEL_INVERT", cBool(d.Invert))
	def("CYD_PANEL_BGR", cBool(d.BGR))
	def("CYD_PANEL_OFFSET_ROTATION", d.OffsetRotation)
	def("CYD_PANEL_HZ", d.Hz)
	def("CYD_BL_PWM", cBool(d.BacklightPWM))
	for _, k := range genLCDPins {
		def("CYD_PIN_LCD_"+k, pinOr(d.Pins, k))
	}
	for _, k := range genRGBTiming {
		def("CYD_RGB_"+k, d.Timing[strings.ToLower(k)])
	}
	for _, k := range []string{"DE_IDLE_HIGH", "PCLK_IDLE_HIGH"} {
		v, ok := d.Timing[strings.ToLower(k)]
		if !ok {
			v = -1
		}
		def("CYD_RGB_"+k, v)
	}
	w.line(0, "")
	w.line(0, "// Touch")
	t := b.Touch
	def("CYD_TOUCH_DRIVER_"+t.Driver, 1)
	def("CYD_TOUCH_BUS_"+strings.ToUpper(t.Bus), 1)
	def("CYD_TOUCH_OFFSET_ROTATION", t.OffsetRotation)
	def("CYD_TOUCH_NEEDS_CAL", cBool(t.NeedsCalibration))
	cal := TouchCalibration{}
	if t.Calibration != nil {
		cal = *t.Calibration
	}
	def("CYD_TOUCH_CAL_X_MIN", cal.XMin)
	def("CYD_TOUCH_CAL_X_MAX", cal.XMax)
	def("CYD_TOUCH_CAL_Y_MIN", cal.YMin)
	def("CYD_TOUCH_CAL_Y_MAX", cal.YMax)
	def("CYD_TOUCH_I2C_ADDR", fmt.Sprintf("0x%02X", t.I2CAddr))
	for _, k := range genTouchPins {
		def("CYD_PIN_TOUCH_"+k, pinOr(t.Pins, k))
	}
	w.line(0, "")
	w.line(0, "// Extras")
	x := b.Extras
	led := RGBLED{R: -1, G: -1, B: -1}
	if x.RGBLED != nil {
		led = *x.RGBLED
	}
	def("CYD_HAS_RGB_LED", cBool(x.RGBLED != nil))
	def("CYD_PIN_LED_R", led.R)
	def("CYD_PIN_LED_G", led.G)
	def("CYD_PIN_LED_B", led.B)
	def("CYD_LED_ACTIVE_LOW", cBool(led.ActiveLow))
	for _, extra := range []struct {
		has, pin string
		v        *int
	}{{"CYD_HAS_LDR", "CYD_PIN_LDR", x.LDR}, {"CYD_HAS_SPEAKER", "CYD_PIN_SPEAKER", x.Speaker}, {"CYD_HAS_SD", "CYD_PIN_SD_CS", x.SDCS}} {
		pin := -1
		if extra.v != nil {
			pin = *extra.v
		}
		def(extra.has, cBool(extra.v != nil))
		def(extra.pin, pin)
	}
	def("CYD_PIN_BOOT", x.BootButton)
	w.line(0, "")
	w.line(0, "// LVGL")
	def("CYD_DRAW_BUF_LINES", b.LVGL.DrawBufferLines)
	def("CYD_DRAW_BUF_DOUBLE", cBool(b.LVGL.DoubleBuffer))
	w.line(0, "")
	w.line(0, "// Project")
	sw, sh := b.ScreenSize(p.Orientation)
	lang := DeviceLanguage(p.Language)
	def("CYD_PROJECT_ID", cString(projectID))
	def("CYD_PROJECT_NAME", cString(p.Name))
	def("CYD_TEMPLATE_VERSION", cString(TemplateVersion))
	def("CYD_SCREEN_W", sw)
	def("CYD_SCREEN_H", sh)
	def("CYD_ROTATION", genRotation(d.NativeOrientation, p.Orientation))
	def("CYD_WIFI_MODE", genWiFiModes[p.Settings.WiFi])
	def("CYD_AURAGO_LINK", cBool(p.Settings.AuraGoLink))
	def("CYD_LANG", cString(lang))
	def("CYD_LANG_"+strings.ToUpper(lang), 1)
	def("CYD_TZ", cString(p.Timezone))
	def("CYD_BACKLIGHT_DEFAULT", p.Settings.Backlight)
	def("CYD_STATUSBAR_CLOCK", cBool(p.Settings.StatusbarClock))
	return w.String()
}

// renderPlatformIOIni writes platformio.ini for one board (plan 1b contract).
func renderPlatformIOIni(p Project, b Board) string {
	var w codeWriter
	w.line(0, "; platformio.ini - generated by CYD Creator (template %s) for board %s. Do not edit.", TemplateVersion, b.ID)
	w.line(0, "[platformio]")
	w.line(0, "default_envs = %s", b.PIOEnv())
	w.line(0, "")
	w.line(0, "[env:%s]", b.PIOEnv())
	w.line(0, "platform = %s", genPlatform)
	w.line(0, "board = %s", b.PIO.Board)
	w.line(0, "framework = arduino")
	w.line(0, "board_build.partitions = partitions.csv")
	w.line(0, "board_build.filesystem = littlefs")
	keys := make([]string, 0, len(b.PIO.BoardBuild))
	for k := range b.PIO.BoardBuild {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, k := range keys {
		w.line(0, "board_build.%s = %s", k, b.PIO.BoardBuild[k])
	}
	w.line(0, "board_upload.flash_size = %dMB", b.FlashMB)
	w.line(0, "monitor_speed = 115200")
	w.line(0, "lib_deps =")
	for _, dep := range genLibDeps(p.Settings.Libraries) {
		w.line(1, "%s", dep)
	}
	w.line(0, "build_flags =")
	for _, f := range genBuildFlags {
		w.line(1, "%s", f)
	}
	for _, f := range b.PIO.BuildFlags {
		w.line(1, "%s", f)
	}
	return w.String()
}

// genLibDeps returns the template dependencies followed by every PIOSpec and
// Depends entry of the selected libraries that is not listed yet, sorted.
func genLibDeps(selected []string) []string {
	out := slices.Clone(genTemplateLibDeps)
	var extra []string
	for _, id := range selected {
		lib, ok := libraryByID(id)
		if !ok {
			continue
		}
		for _, spec := range append([]string{lib.PIOSpec}, lib.Depends...) {
			if !slices.Contains(out, spec) && !slices.Contains(extra, spec) {
				extra = append(extra, spec)
			}
		}
	}
	slices.Sort(extra)
	return append(out, extra...)
}
