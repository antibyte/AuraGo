// Build the pinned Storymaker renderer without network access or automatic clocks.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const directory = path.join(root, 'ui/js/vendor/storymaker');
const versions = { 'pixi.js': '8.22.0', gsap: '3.15.1' };
const notices = [];
for (const [name, version] of Object.entries(versions)) {
    const base = path.join(root, 'node_modules', name);
    const pkg = JSON.parse(await readFile(path.join(base, 'package.json'), 'utf8'));
    if (pkg.version !== version) throw new Error(`${name}: expected ${version}, got ${pkg.version}`);
    const license = name === 'gsap'
        ? pkg.license + '\n\n' + (await readFile(path.join(base, 'gsap-core.js'), 'utf8')).match(/\/\*![\s\S]*?\*\//)?.[0] + '\n'
        : await readFile(path.join(base, 'LICENSE'), 'utf8');
    notices.push(`${name} ${version}\n\n${license}`);
}
// Vendor bookkeeping must not access the scene's blocked clocks or run its own loop.
const prelude = `(function(){
var Date = { now: function(){ return 0; } };
var performance = { now: function(){ return 0; } };
var setTimeout = function(){ return 0; }, clearTimeout = function(){};
var requestAnimationFrame = function(){ return 0; }, cancelAnimationFrame = function(){};
var Math = Object.create(globalThis.Math), seed = 1;
Math.random = function(){ seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; };
`;
const result = await build({ absWorkingDir: root, entryPoints: ['assets/storymaker/runtime-entry.mjs'], bundle: true,
    write: false, format: 'iife', globalName: 'StorymakerVendor', platform: 'browser', target: 'es2020',
    minify: true, legalComments: 'none', treeShaking: true, metafile: true,
    banner: { js: '/* Generated by scripts/build-storymaker-vendor.mjs. */\n' + prelude },
    footer: { js: 'StorymakerVendor.gsap.ticker.sleep();globalThis.StorymakerVendor=StorymakerVendor;})();' } });
const bytes = result.outputFiles[0].contents;
const packages=new Set();
for(const input of Object.keys(result.metafile.inputs)){
    const match=/^node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input.replaceAll('\\','/'));
    if(match&&!versions[match[1]])packages.add(match[1]);
}
for(const name of [...packages].sort()){
    const base=path.join(root,'node_modules',name),pkg=JSON.parse(await readFile(path.join(base,'package.json'),'utf8'));
    const license=(await readdir(base)).find(f=>/^licen[sc]e(?:\.md|\.txt)?$/i.test(f));
    if(!license&&name!=='@pixi/colord')throw new Error(`Missing bundled dependency license: ${name}`);
    const source=license?path.join(base,license):path.join(root,'licences/storymaker-colord-LICENSE.txt');
    notices.push(`${name} ${pkg.version}\n\n${await readFile(source,'utf8')}`);
}
if (bytes.byteLength > 2 * 1048576) throw new Error('Storymaker vendor exceeds 2 MiB');
const outputs = new Map([
    ['runtime.js', bytes],
    ['LICENSES.txt', notices.join('\n\n---\n\n')],
    ['manifest.json', JSON.stringify({ versions, bytes: bytes.byteLength, sha256: createHash('sha256').update(bytes).digest('hex') }, null, 2) + '\n']
]);
await mkdir(directory, { recursive: true });
for (const [name, data] of outputs) {
    const file = path.join(directory, name);
    if (process.argv.includes('--check')) {
        if (!Buffer.from(await readFile(file)).equals(Buffer.from(data))) throw new Error(`Stale vendor file: ${name}`);
    } else await writeFile(file, data);
}
console.log(`Storymaker vendor: ${bytes.byteLength} bytes; ${process.argv.includes('--check') ? 'verified' : 'built'}`);
