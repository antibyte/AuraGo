import assert from 'node:assert/strict';
import { mkdtemp, mkdir, copyFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const temp = await mkdtemp(path.join(tmpdir(), 'aurago-ziro-bridge-'));
const local = new Map();
const encoder = new TextEncoder();
const parent = { postMessage() {} };
globalThis.window = Object.assign(new EventTarget(), { parent });
globalThis.document = Object.assign(new EventTarget(), { readyState: 'complete' });
globalThis.location = { hash: '#aurago_ziro=test-secret&parent_origin=http%3A%2F%2Fdesktop.test', pathname: '/', search: '' };
globalThis.history = { replaceState() {} };
globalThis.localStorage = { setItem: (key, value) => local.set(key, value), getItem: key => local.get(key) || null, removeItem: key => local.delete(key) };
try {
  await mkdir(path.join(temp, 'home'));
  await mkdir(path.join(temp, 'node_modules/@ziroeda/wx'), { recursive: true });
  await writeFile(path.join(temp, 'node_modules/@ziroeda/wx/package.json'), '{"type":"module","exports":{"./filefn.js":"./filefn.js"}}');
  await writeFile(path.join(temp, 'node_modules/@ziroeda/wx/filefn.js'), 'export class MEMORY_FILESYSTEM { files=new Map(); listener=null; Write(name,bytes){this.files.set(name,bytes);this.listener?.(name,bytes);} Read(name){return this.files.get(name);} SetWriteListener(listener){this.listener=listener;} } export function wxMountFileSystem(path,fs){globalThis.ziroMount={path,fs};return ()=>{};}');
  await writeFile(path.join(temp, 'package.json'), '{"type":"module"}');
  await writeFile(path.join(temp, 'home/projectStore.js'), 'const records=new Map();export async function loadProject(id){return records.get(id)||null;} export async function saveProject(name,files,id){if(globalThis.ziroStoreGate){globalThis.ziroStoreStarted();await globalThis.ziroStoreGate;}records.set(id,{name,files});return id;} export async function updateProjectFiles(id,files){const rec=records.get(id);if(rec)for(const f of files){const i=rec.files.findIndex(old=>old.name===f.name);if(i<0)rec.files.push(f);else rec.files[i]=f;}}');
  await writeFile(path.join(temp, 'home/new_project.js'), 'export function newProjectFiles(name){return [{name:name+"/"+name+".kicad_pro",text:"{}"}];}');
  await copyFile(new URL('../internal/desktopstore/ziro_designer_assets/aurago_bridge.ts', import.meta.url), path.join(temp, 'bridge.ts'));
  const bridge = await import(pathToFileURL(path.join(temp, 'bridge.ts')).href);
  let files = [], fails = false;
  const dispose = bridge.installAuraGoBridge({ open: value => { files = value; }, snapshot: () => { if (fails) throw new Error('serialization failed'); return files; } });
  const dispatch = (source, origin, challenge, port) => {
    const event = new Event('message');
    Object.assign(event, { source, origin, data: { ziro: 1, type: 'connect', challenge }, ports: [port] });
    window.dispatchEvent(event);
  };
  const invalid = new MessageChannel();
  dispatch({}, 'http://desktop.test', 'test-secret', invalid.port1);
  dispatch(parent, 'http://evil.test', 'test-secret', invalid.port1);
  dispatch(parent, 'http://desktop.test', 'wrong-secret', invalid.port1);
  const channel = new MessageChannel();
  dispatch(parent, 'http://desktop.test', 'test-secret', channel.port1);
  let sequence = 0;
  const waiting = new Map();
  channel.port2.onmessage = event => {
    const data = event.data;
    if (data.type === 'save-request') { channel.port2.postMessage({ ziro: 1, reply: data.id, ok: false }); return; }
    const waiter = waiting.get(data.reply);
    if (waiter) { clearTimeout(waiter.timer); waiting.delete(data.reply); waiter.resolve(data); }
  };
  const call = (type, payload = {}) => new Promise((resolve, reject) => {
    const id = ++sequence;
    const timer = setTimeout(() => reject(new Error('bridge timeout: ' + type)), 2000);
    waiting.set(id, { resolve, timer }); channel.port2.postMessage({ ziro: 1, id, type, payload });
  });
  const original = [{ name: 'Board.kicad_pro', bytes: encoder.encode('{}') }, { name: 'model.bin', bytes: Uint8Array.of(0,255,128) }];
  assert.equal((await call('open', { projectKey: 'Shared/A/Board', draftKey: 'window1', files: original })).error, undefined);
  assert.equal(bridge.auraGoProjectId(), 'aurago:Shared/A/Board:window1');
  assert.equal(globalThis.ziroMount.path, '/Board');
  assert.deepEqual([...globalThis.ziroMount.fs.Read('model.bin')], [0,255,128]);
  const projectRead = Reflect.get(globalThis, '__auragoZiroProjectRead');
  assert.deepEqual([...projectRead('/Board/model.bin')], [0,255,128]);
  assert.equal(projectRead('/Board/missing'), null);
  assert.equal(projectRead('/BoardTwo/model.bin'), undefined);
  const copy = projectRead('/Board/model.bin'); copy[0] = 99;
  assert.deepEqual([...projectRead('/Board/model.bin')], [0,255,128]);
  bridge.auraGoChanged([{ name: 'new/sub.kicad_sch', text: 'fresh' }]);
  assert.equal(new TextDecoder().decode(globalThis.ziroMount.fs.Read('new/sub.kicad_sch')), 'fresh');
  let result = await call('snapshot');
  assert.ok(result.payload.files.some(file => file.name === 'new/sub.kicad_sch'));
  assert.deepEqual([...result.payload.files.find(file => file.name === 'model.bin').bytes], [0,255,128]);
  assert.equal(local.get('aurago-ziro-draft:' + bridge.auraGoProjectId()), '1');
  fails = true;
  assert.equal((await call('snapshot')).error, 'serialization failed');
  fails = false;
  const guard = event => event.preventDefault();
  window.addEventListener('beforeunload', guard);
  assert.equal((await call('snapshot')).error, 'ziro.save_failed');
  window.removeEventListener('beforeunload', guard);
  result = await call('snapshot');
  const savedGeneration = result.payload.generation;
  bridge.auraGoChanged([{ name: 'new/sub.kicad_sch', text: 'later change' }]);
  await call('saved', { generation: savedGeneration, projectKey: 'Shared/A/Board' });
  assert.equal(local.get('aurago-ziro-draft:' + bridge.auraGoProjectId()), '1', 'an older acknowledgement cannot clear newer changes');
  result = await call('snapshot');
  await call('saved', { generation: result.payload.generation, projectKey: 'Shared/A/Board' });
  assert.equal(local.get('aurago-ziro-draft:' + bridge.auraGoProjectId()), undefined);
  await assert.rejects(bridge.auraGoSave(), /save_failed/);
  await call('open', { projectKey: 'Shared/B/Board', draftKey: 'window1', files: original });
  assert.equal(bridge.auraGoProjectId(), 'aurago:Shared/B/Board:window1');
  await call('new', { name: 'New', draftKey: 'window2' });
  assert.equal((await call('snapshot')).payload.files[0].name, 'New.kicad_pro');
  const newId = bridge.auraGoProjectId();
  await call('draft', { draftKey: 'window2' });
  await call('cancel-open');
  assert.equal(local.get('aurago-ziro-draft:' + newId), '1', 'cancelled recovery preserves the draft');
  assert.equal((await call('draft', { draftKey: 'window2' })).payload.draft, true);
  await call('recover');
  assert.equal(bridge.auraGoProjectId(), newId);
  const previousFiles = files;
  let release;
  const started = new Promise(resolve => { globalThis.ziroStoreStarted = resolve; });
  globalThis.ziroStoreGate = new Promise(resolve => { release = resolve; });
  channel.port2.postMessage({ ziro: 1, id: 9999, type: 'new', payload: { name: 'Late', draftKey: 'closed' } });
  await started;
  dispose(); release();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(files, previousFiles, 'a late storage completion cannot reopen a disposed editor');
  invalid.port1.close(); invalid.port2.close(); channel.port2.close();
  assert.equal(Reflect.has(globalThis, '__auragoZiroProjectRead'), false);
  console.log('Ziro bridge: source/origin/challenge checks, project identity, binary/new files, strict serialization, acknowledgements and disposal passed.');
} finally { await rm(temp, { recursive: true, force: true }); }
