import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'assets/aura-drift/runtime-entry.mjs');
const outDir = path.join(root, 'ui/js/vendor/aura-drift');
const runtimePath = path.join(outDir, 'three-runtime.js');
const licensePath = path.join(outDir, 'LICENSE.txt');
const manifestPath = path.join(outDir, 'manifest.json');
const checkOnly = process.argv.includes('--check');
const THREE_VERSION = '0.186.1';
const MAX_BYTES = 1.2 * 1024 * 1024;
const dependencyRoot = path.resolve(process.env.AURAGO_AURA_DRIFT_VENDOR_NODE_MODULES || path.join(root, 'node_modules'));
const requireFromDependencies = createRequire(path.join(dependencyRoot, 'package.json'));
const { build } = requireFromDependencies('esbuild');

const pkg = JSON.parse(await readFile(path.join(dependencyRoot, 'three/package.json'), 'utf8'));
if (pkg.version !== THREE_VERSION) {
    console.error(`Aura Drift needs three ${THREE_VERSION}, found ${pkg.version}`);
    process.exit(1);
}

const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile: runtimePath,
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'AuraDriftThree',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    legalComments: 'none',
    treeShaking: true,
    nodePaths: [dependencyRoot],
    banner: { js: '/* Generated by scripts/build-aura-drift-vendor.mjs. Do not edit by hand. */' },
    logLevel: 'silent'
});
const output = result.outputFiles.find(file => path.resolve(file.path) === runtimePath);
if (!output) throw new Error('esbuild did not produce the Aura Drift runtime');
// `var AuraDriftThree` at the top level of a classic script already becomes window.AuraDriftThree.
const contents = Buffer.from(output.contents);
if (contents.byteLength > MAX_BYTES) {
    console.error(`Aura Drift runtime is ${contents.byteLength} bytes, over the ${MAX_BYTES} byte budget`);
    process.exit(1);
}
const sha256 = createHash('sha256').update(contents).digest('hex');
const licenseText = (await readFile(path.join(dependencyRoot, 'three/LICENSE'), 'utf8')).trim();
const license = `Three.js ${THREE_VERSION} (MIT), bundled with AuraGo Aura Drift.\n\n${licenseText}\n`;
const manifest = JSON.stringify({ three: THREE_VERSION, bytes: contents.byteLength, sha256 }, null, 2) + '\n';

async function same(file, expected) {
    try { return Buffer.compare(await readFile(file), Buffer.from(expected)) === 0; }
    catch (_) { return false; }
}

if (checkOnly) {
    const ok = (await Promise.all([same(runtimePath, contents), same(licensePath, license), same(manifestPath, manifest)])).every(Boolean);
    if (!ok) {
        console.error('Aura Drift vendor output is stale; run node scripts/build-aura-drift-vendor.mjs');
        process.exitCode = 1;
    } else {
        console.log(`Aura Drift vendor is current (${contents.byteLength} bytes, SHA-256 ${sha256.slice(0, 16)}...).`);
    }
} else {
    await mkdir(outDir, { recursive: true });
    await Promise.all([writeFile(runtimePath, contents), writeFile(licensePath, license, 'utf8'), writeFile(manifestPath, manifest, 'utf8')]);
    console.log(`Built ${path.relative(root, runtimePath)} (${contents.byteLength} bytes, SHA-256 ${sha256.slice(0, 16)}...).`);
}
