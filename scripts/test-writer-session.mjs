import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const timers=new Map();let clock=0,id=0;
const context={window:{},setTimeout:(fn,ms)=>{timers.set(++id,{fn,time:clock+ms});return id;},clearTimeout:id=>timers.delete(id)};
vm.runInNewContext(readFileSync('ui/js/desktop/apps/writer-session.js','utf8'),context);
const create=context.window.WriterSession.create;
const tick=async ms=>{clock+=ms;for(const [id,timer] of [...timers])if(timer.time<=clock){timers.delete(id);timer.fn();}for(let n=0;n<12;n++)await Promise.resolve();};
const deferred=()=>{let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b;});return {promise,resolve,reject};};
let writes=0,active=0,maxActive=0,states=[],pending=deferred();
const q=create({serialize:async()=>new Uint8Array([1]),write:async()=>{writes++;maxActive=Math.max(maxActive,++active);await pending.promise;active--;},onState:s=>states.push(s)});
q.changed();await tick(799);assert.equal(writes,0);await tick(1);assert.equal(writes,1);
q.changed();await tick(1000);assert.equal(writes,1,'No parallel save');
const first=pending;pending=deferred();first.resolve();await tick(0);assert.equal(q.dirty,true,'An old response cannot mark newer changes clean');
await tick(800);assert.equal(writes,2);pending.resolve();await q.save();assert.equal(q.dirty,false);assert.equal(maxActive,1);
q.dispose();timers.clear();
let saved=0;
const continuous=create({serialize:async()=>[],write:async()=>{saved++;}});
for(let n=0;n<10;n++){continuous.changed();await tick(500);}
assert.ok(saved>=1,'Continuous typing saves within five seconds');continuous.dispose();timers.clear();
let fail=true,attempts=0;
const retry=create({serialize:async()=>[],write:async()=>{attempts++;if(fail)throw Error('offline');}});
retry.changed();await tick(800);assert.equal(retry.dirty,true);assert.ok(retry.error);await tick(10000);assert.equal(attempts,1,'No retry storm');
fail=false;await retry.save();assert.equal(retry.dirty,false);retry.dispose();
let pausedWrites=0;
const paused=create({serialize:async()=>[],write:async()=>{pausedWrites++;}});
paused.changed();paused.suspend();await tick(6000);assert.equal(pausedWrites,0);
paused.changed();await tick(6000);assert.equal(pausedWrites,0);paused.resume();await tick(800);assert.equal(pausedWrites,1);paused.dispose();
const disposed=create({serialize:async()=>[],write:async()=>{throw Error('disposed write');}});
disposed.changed();disposed.dispose();await tick(1000);
await assert.rejects(disposed.save(),/closed/);
console.log('Writer sessions: debounce, maximum delay, single-flight, revision acknowledgement, errors, retry and disposal pass');
