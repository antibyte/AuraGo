import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'assets/stickers/production.json'), 'utf8'));
const items = manifest.items.map(({ id, category, style }) => ({ id, category, style, width: 1024, height: 1024,
    image: '/img/stickers/' + id + '.png', thumbnail: '/img/stickers/thumbs/' + id + '.png' }));
assert.equal(items.length, 100);
assert.equal(new Set(items.map(item => item.id)).size, 100);
for (const item of items) assert.match(item.id, /^[a-z]+-[a-z-]+$/);
for (const key of ['category', 'style']) {
    const values = new Set(items.map(item => item[key])); assert.equal(values.size, 10);
    for (const value of values) assert.equal(items.filter(item => item[key] === value).length, 10);
}
for (const category of new Set(items.map(item => item.category))) assert.equal(new Set(items.filter(item => item.category === category).map(item => item.style)).size, 10);
const catalog = '// Generated by scripts/build-stickers.mjs from assets/stickers/production.json.\n' +
    '(function () {\n    window.AuraStickerCatalog = Object.freeze([\n' + items.map(item => '        ' + JSON.stringify(item)).join(',\n') + '\n    ].map(Object.freeze));\n})();\n';
const catalogPath = path.join(root, 'ui/js/desktop/shared/sticker-catalog.js');
const english = JSON.parse(fs.readFileSync(path.join(root, 'ui/lang/desktop/en.json'), 'utf8'));
const html = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>100 studio stickers</title><style>body{margin:30px;background:#dbe0e7;color:#172031;font:15px system-ui}h1{font-size:30px}main{display:grid;grid-template-columns:repeat(auto-fit,minmax(330px,1fr));gap:16px}figure{margin:0;background:white;border-radius:12px;overflow:hidden}.pair{display:flex}.pair img{width:50%;aspect-ratio:1;object-fit:contain;background:#f5f3ee}.pair img+img{background:#20242b}figcaption{padding:12px}small{display:block;color:#596476;margin-top:4px}a{color:inherit}p{max-width:75ch}</style><h1>100 studio stickers</h1><p>Ten themes, ten styles. Each sticker is shown on a light and dark background. Select its name to inspect the 1024 × 1024 RGBA original. Both apps use the same files.</p><main>' +
    items.map(item => '<figure><div class="pair"><img loading="lazy" alt="" src="../../ui' + item.thumbnail + '"><img loading="lazy" alt="" src="../../ui' + item.thumbnail + '"></div><figcaption><a href="../../ui' + item.image + '">' + english['stickers.name.' + item.id] + '</a><small>' + item.id + ' · ' + english['stickers.style.' + item.style] + '</small></figcaption></figure>').join('\n') + '</main></html>\n';
const contactPath = path.join(root, 'assets/stickers/contact-sheet.html');
if (process.argv.includes('--check')) {
    assert.equal(fs.readFileSync(catalogPath, 'utf8').replace(/\r\n/g, '\n'), catalog, 'Regenerate the sticker catalog');
    assert.equal(fs.readFileSync(contactPath, 'utf8').replace(/\r\n/g, '\n'), html, 'Regenerate the contact sheet');
    const hashes = new Set();
    for (const item of items) for (const [key, size] of [['image', 1024], ['thumbnail', 192]]) {
        const bytes = fs.readFileSync(path.join(root, 'ui', item[key]));
        assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', item.id);
        assert.equal(bytes.readUInt32BE(16), size, item.id); assert.equal(bytes.readUInt32BE(20), size, item.id);
        assert.equal(bytes[25], 6, item.id + ' must have an RGBA channel');
        if (key === 'image') hashes.add(crypto.createHash('sha256').update(bytes).digest('hex'));
    }
    assert.equal(hashes.size, 100, 'Duplicate images');
    for (const locale of ['cs', 'da', 'de', 'el', 'en', 'es', 'fr', 'hi', 'it', 'ja', 'nl', 'no', 'pl', 'pt', 'sv', 'zh']) {
        const raw = fs.readFileSync(path.join(root, 'ui/lang/desktop', locale + '.json'), 'utf8'), strings = JSON.parse(raw);
        const keys = [...raw.matchAll(/"(stickers\.[^"]+)"\s*:/g)].map(match => match[1]);
        assert.equal(keys.length, new Set(keys).size, locale + ': duplicate sticker translations');
        for (const key of Object.keys(english).filter(key => key.startsWith('stickers.'))) assert.ok(strings[key]?.trim(), locale + ': ' + key);
        for (const item of items) for (const key of ['name.' + item.id, 'category.' + item.category, 'style.' + item.style]) assert.ok(strings['stickers.' + key]?.trim(), locale + ': ' + key);
    }
    console.log('100 unique RGBA stickers and thumbnails, balanced categories/styles and 16 locales verified.');
} else {
    fs.writeFileSync(catalogPath, catalog);
    fs.writeFileSync(contactPath, html);
    console.log('Generated shared sticker catalog.');
}
