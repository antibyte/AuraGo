import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'ui/js/desktop/theme-fx');
const outDir = path.join(root, 'ui/js/vendor/desktop-themes');
const bundles = [
    { entry: 'voxel-runtime-entry.js', out: 'voxel-runtime.js', label: 'voxel' },
    { entry: 'orbit-runtime-entry.js', out: 'orbit-runtime.js', label: 'orbit' }
].map(bundle => ({
    ...bundle,
    source: path.join(sourceDir, bundle.entry),
    outPath: path.join(outDir, bundle.out)
}));
const licensesOut = path.join(outDir, 'LICENSES.txt');
const checkOnly = process.argv.includes('--check');
const dependencyRoot = path.resolve(process.env.AURAGO_DESKTOP_THEME_VENDOR_NODE_MODULES || path.join(root, 'node_modules'));
const requireFromDependencies = createRequire(path.join(dependencyRoot, 'package.json'));
const { build } = requireFromDependencies('esbuild');

const packages = [
    { name: 'Three.js', version: '0.186.1', license: 'MIT', path: 'three/LICENSE' },
    { name: 'Rapier3D Compat', version: '0.21.0', license: 'Apache-2.0', path: '@dimforge/rapier3d-compat/LICENSE' }
];

const licenseSections = [];
for (const pkg of packages) {
    const licensePath = path.join(dependencyRoot, pkg.path);
    const licenseText = (await readFile(licensePath, 'utf8')).trim();
    licenseSections.push(`${pkg.name} ${pkg.version} (${pkg.license})\n${licenseText}`);
}
const licenses = `Third-party licenses bundled with AuraGo Desktop theme effects (Voxel World, Orbit).\n\n${licenseSections.join('\n\n---\n\n')}\n`;

async function buildBundle(bundle) {
    const result = await build({
        absWorkingDir: root,
        entryPoints: [bundle.source],
        outfile: bundle.outPath,
        bundle: true,
        write: false,
        format: 'esm',
        platform: 'browser',
        target: ['es2022'],
        minify: true,
        legalComments: 'none',
        treeShaking: true,
        nodePaths: [dependencyRoot],
        banner: { js: '/* Generated by scripts/build-desktop-theme-vendor.mjs. Do not edit by hand. */' },
        logLevel: 'silent'
    });

    const runtime = result.outputFiles.find(file => path.resolve(file.path) === bundle.outPath);
    if (!runtime) throw new Error(`esbuild did not produce the ${bundle.label} runtime bundle`);
    return { ...bundle, contents: runtime.contents };
}

async function checkFile(filePath, expected) {
    let actual;
    try { actual = await readFile(filePath); }
    catch (_) { return false; }
    return Buffer.compare(Buffer.from(actual), Buffer.from(expected)) === 0;
}

function shortDigest(contents) {
    return createHash('sha256').update(contents).digest('hex').slice(0, 16);
}

const runtimes = await Promise.all(bundles.map(buildBundle));

if (checkOnly) {
    const checks = await Promise.all([
        ...runtimes.map(runtime => checkFile(runtime.outPath, runtime.contents)),
        checkFile(licensesOut, Buffer.from(licenses))
    ]);
    if (!checks.every(Boolean)) {
        console.error('Desktop theme vendor output is stale; run node scripts/build-desktop-theme-vendor.mjs');
        process.exitCode = 1;
    } else {
        const digests = runtimes.map(runtime => `${runtime.label} ${shortDigest(runtime.contents)}…`).join(', ');
        console.log(`Desktop theme vendor is current (SHA-256 ${digests}).`);
    }
} else {
    const { writeFile } = await import('node:fs/promises');
    await mkdir(outDir, { recursive: true });
    await Promise.all([
        ...runtimes.map(runtime => writeFile(runtime.outPath, runtime.contents)),
        writeFile(licensesOut, licenses, 'utf8')
    ]);
    for (const runtime of runtimes) {
        console.log(`Built ${path.relative(root, runtime.outPath)} (${runtime.contents.byteLength} bytes, SHA-256 ${shortDigest(runtime.contents)}…).`);
    }
}
