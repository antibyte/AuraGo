import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'ui/js/desktop/theme-fx/voxel-runtime-entry.js');
const outDir = path.join(root, 'ui/js/vendor/desktop-themes');
const out = path.join(outDir, 'voxel-runtime.js');
const licensesOut = path.join(outDir, 'LICENSES.txt');
const checkOnly = process.argv.includes('--check');
const dependencyRoot = path.resolve(process.env.AURAGO_DESKTOP_THEME_VENDOR_NODE_MODULES || path.join(root, 'node_modules'));
const requireFromDependencies = createRequire(path.join(dependencyRoot, 'package.json'));
const { build } = requireFromDependencies('esbuild');

const packages = [
    { name: 'Three.js', version: '0.186.1', license: 'MIT', path: 'three/LICENSE' },
    { name: 'Rapier3D Compat', version: '0.21.0', license: 'Apache-2.0', path: '@dimforge/rapier3d-compat/LICENSE' }
];

const licenseSections = [];
for (const pkg of packages) {
    const licensePath = path.join(dependencyRoot, pkg.path);
    const licenseText = (await readFile(licensePath, 'utf8')).trim();
    licenseSections.push(`${pkg.name} ${pkg.version} (${pkg.license})\n${licenseText}`);
}
const licenses = `Third-party licenses bundled with AuraGo Desktop voxel theme effects.\n\n${licenseSections.join('\n\n---\n\n')}\n`;

const result = await build({
    absWorkingDir: root,
    entryPoints: [source],
    outfile: out,
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    legalComments: 'none',
    treeShaking: true,
    nodePaths: [dependencyRoot],
    banner: { js: '/* Generated by scripts/build-desktop-theme-vendor.mjs. Do not edit by hand. */' },
    logLevel: 'silent'
});

const runtime = result.outputFiles.find(file => path.resolve(file.path) === out);
if (!runtime) throw new Error('esbuild did not produce the voxel runtime bundle');

async function checkFile(filePath, expected) {
    let actual;
    try { actual = await readFile(filePath); }
    catch (_) { return false; }
    return Buffer.compare(Buffer.from(actual), Buffer.from(expected)) === 0;
}

if (checkOnly) {
    const valid = await checkFile(out, runtime.contents) && await checkFile(licensesOut, Buffer.from(licenses));
    if (!valid) {
        console.error('Desktop theme vendor output is stale; run node scripts/build-desktop-theme-vendor.mjs');
        process.exitCode = 1;
    } else {
        const digest = createHash('sha256').update(runtime.contents).digest('hex');
        console.log(`Desktop theme vendor is current (SHA-256 ${digest.slice(0, 16)}…).`);
    }
} else {
    await mkdir(outDir, { recursive: true });
    await Promise.all([
        import('node:fs/promises').then(({ writeFile }) => writeFile(out, runtime.contents)),
        import('node:fs/promises').then(({ writeFile }) => writeFile(licensesOut, licenses, 'utf8'))
    ]);
    const digest = createHash('sha256').update(runtime.contents).digest('hex');
    console.log(`Built ${path.relative(root, out)} (${runtime.contents.byteLength} bytes, SHA-256 ${digest.slice(0, 16)}…).`);
}
