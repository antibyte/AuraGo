"""Verify an OCI export and record its actual index/config digests for AuraGo."""
import hashlib
import json
from pathlib import Path
import sys
import tarfile

root = Path(__file__).resolve().parents[2]
archive_path, metadata_path = map(Path, sys.argv[1:3])
metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
digest = metadata["containerimage.digest"]
configs = {}
with tarfile.open(archive_path, "r") as archive:
    def blob(reference):
        algorithm, value = reference.split(":")
        assert algorithm == "sha256" and len(value) == 64
        member = archive.getmember("blobs/sha256/" + value)
        assert member.size <= 4 << 20
        data = archive.extractfile(member).read()
        assert hashlib.sha256(data).hexdigest() == value
        return json.loads(data)
    index = blob(digest)
    for manifest in index["manifests"]:
        platform = manifest.get("platform", {})
        if platform.get("os") != "linux":
            continue
        arch = platform.get("architecture")
        assert arch in ("amd64", "arm64") and arch not in configs
        image = blob(manifest["digest"])
        config_digest = image["config"]["digest"]
        config = blob(config_digest)
        assert config["architecture"] == arch and config["os"] == "linux"
        assert config["config"]["Labels"]["aurago.ocr.version"] == "1.1.2"
        assert config["config"]["Labels"]["aurago.ocr.model_revision"] == "bd02167fdf2005a19962cc15188f8496a2c87d3b"
        configs[arch] = config_digest
assert set(configs) == {"amd64", "arm64"}, configs
source = "// Code generated by scripts/ocr/pin_image.py from a verified OCI export. DO NOT EDIT.\npackage ocr\n\n"
source += 'const ReleaseImage = "ghcr.io/antibyte/aurago-ocr@' + digest + '"\n\n'
source += "var releaseConfigIDs = map[string]string{\n"
for arch, config in sorted(configs.items()):
    source += '    "' + arch + '": "' + config + '",\n'
source += "}\n"
(root / "internal/ocr/release.go").write_text(source, encoding="utf-8", newline="\n")
print("Pinned", digest, configs)
