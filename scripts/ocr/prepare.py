"""Resolve a pip --dry-run --report into hash pins and the fixed HF inventory."""
import hashlib
import json
from pathlib import Path
import sys
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]
REVISION = "bd02167fdf2005a19962cc15188f8496a2c87d3b"
BASE = "https://huggingface.co/datalab-to/indra-ocr/"


def fetch(url):
    with urlopen(url, timeout=90) as response:
        data = response.read(4 << 20)
        if response.read(1):
            raise ValueError("metadata too large")
        return data


def main(report_path):
    report = json.loads(Path(report_path).read_text(encoding="utf-8"))
    assert any(x["metadata"]["name"] == "indra-ocr" and x["metadata"]["version"] == "1.1.2" for x in report["install"])
    lines = ["# Generated by scripts/ocr/prepare.py from the pinned Python 3.12 Linux resolver."]
    for entry in report["install"]:
        name, version = entry["metadata"]["name"], entry["metadata"]["version"]
        package = json.loads(fetch("https://pypi.org/pypi/" + name + "/" + version + "/json"))
        hashes = sorted({item["digests"]["sha256"] for item in package["urls"]})
        assert hashes and all(len(h) == 64 for h in hashes)
        continuation = " " + chr(92) + "\n    "
        lines.append(name + "==" + version + continuation + continuation.join("--hash=sha256:" + h for h in hashes))
    (ROOT / "internal/ocr/runtime/requirements.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    metadata = json.loads(fetch("https://huggingface.co/api/models/datalab-to/indra-ocr/revision/" + REVISION + "?blobs=true"))
    assert metadata["sha"] == REVISION
    files = []
    for item in metadata["siblings"]:
        name = item["rfilename"]
        if "/" in name or name.startswith("math"):
            continue
        if not (name.endswith(".onnx") or name == "meta.json" or name == "lm.npz" or (name.startswith("lm_") and name.endswith(".npz"))):
            continue
        if item.get("lfs"):
            digest, size = item["lfs"]["sha256"], item["lfs"]["size"]
        else:
            data = fetch(BASE + "resolve/" + REVISION + "/" + name)
            digest, size = hashlib.sha256(data).hexdigest(), len(data)
        files.append(dict(name=name, size=size, sha256=digest))
    assert {"det.onnx", "rec.onnx", "rec_rtl.onnx", "rec_cjk.onnx", "rec_world.onnx", "order.onnx", "meta.json"} <= {f["name"] for f in files}
    manifest = dict(revision=REVISION, files=sorted(files, key=lambda f: f["name"]))
    (ROOT / "internal/ocr/runtime/models.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    license_text = fetch(BASE + "resolve/" + REVISION + "/LICENSE")
    (ROOT / "licences/texts/Indra-OCR-models.txt").write_bytes(license_text)
    (ROOT / "internal/ocr/runtime/LICENSE-MODELS.txt").write_bytes(license_text)
    print("Locked", len(report["install"]), "packages and", len(files), "model files.")


if __name__ == "__main__":
    main(sys.argv[1])
