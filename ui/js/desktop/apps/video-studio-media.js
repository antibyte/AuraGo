(function () {
    'use strict';

    const FPS = 30;
    const THUMB_COUNT = 8;
    const THUMB_WIDTH = 160;
    const MAX_PEAK_BYTES = 80 * 1024 * 1024;
    // Exactly the names the editor gives its own PNGs (title-<Date.now()>.png, sticker-<name>.png), so a
    // user's own "title-holiday.png" stays visible in the media bin.
    const ARTWORK_NAME = /^(title-\d{12,}|sticker-(sparkle|heart|sun|star|flower|burst))\.png$/;

    // Frames spread over the clip, starting just after the first frame (which is often black).
    function thumbnailTimes(durationFrames, count) {
        const duration = Math.max(0, Math.floor(Number(durationFrames) || 0));
        if (duration <= 0) return [0];
        const n = Math.max(1, Math.min(Number(count) || THUMB_COUNT, duration));
        const frames = [];
        for (let i = 0; i < n; i++) {
            const frame = Math.min(duration - 1, Math.round(duration * (0.03 + 0.96 * i / n)));
            if (!frames.includes(frame)) frames.push(frame);
        }
        return frames;
    }

    function peaksFromChannels(channels, sampleRate, perSecond, cap) {
        const length = channels && channels[0] ? channels[0].length : 0;
        if (!length || !sampleRate) return new Float32Array(0);
        const buckets = Math.max(1, Math.min(Number(cap) || 6000, Math.ceil(length / sampleRate * (Number(perSecond) || 50))));
        const size = length / buckets;
        const peaks = new Float32Array(buckets);
        for (let b = 0; b < buckets; b++) {
            const from = Math.floor(b * size), to = Math.max(from + 1, Math.floor((b + 1) * size));
            let peak = 0;
            for (const channel of channels) {
                for (let i = from; i < to && i < length; i++) {
                    const value = Math.abs(channel[i]);
                    if (value > peak) peak = value;
                }
            }
            peaks[b] = peak;
        }
        return peaks;
    }

    function pickThumb(thumbs, frame) {
        if (!thumbs || !thumbs.length) return null;
        let best = thumbs[0];
        for (const thumb of thumbs) if (Math.abs(thumb.frame - frame) < Math.abs(best.frame - frame)) best = thumb;
        return best;
    }

    // Title and sticker PNGs are generated by the editor itself; the media bin hides them.
    function isArtwork(asset) {
        return !!asset && asset.kind === 'image' && ARTWORK_NAME.test(String(asset.name || ''));
    }

    function hasWaveform(asset) {
        return !!asset && (asset.kind === 'audio' || asset.kind === 'video' && asset.has_audio);
    }

    function create(options) {
        const opts = options || {};
        const thumbs = new Map(), peaks = new Map(), urls = new Set(), queue = [];
        const abort = new AbortController();
        let running = false, disposed = false, video = null;

        function notify(assetId) { if (!disposed && typeof opts.onUpdate === 'function') opts.onUpdate(assetId); }

        function once(el, name, timeout) {
            return new Promise((resolve, reject) => {
                const done = (ok, value) => { clearTimeout(timer); el.removeEventListener(name, onEvent); el.removeEventListener('error', onError); abort.signal.removeEventListener('abort', onAbort); ok ? resolve(value) : reject(value); };
                const onEvent = () => done(true);
                const onError = () => done(false, new Error('media_error'));
                const onAbort = () => done(false, new Error('aborted'));
                const timer = setTimeout(() => done(false, new Error('timeout')), timeout);
                el.addEventListener(name, onEvent);
                el.addEventListener('error', onError);
                abort.signal.addEventListener('abort', onAbort);
            });
        }

        function canvasURL(canvas) {
            return new Promise(resolve => canvas.toBlob(blob => {
                if (!blob || disposed) return resolve('');
                const url = URL.createObjectURL(blob);
                urls.add(url);
                resolve(url);
            }, 'image/jpeg', 0.72));
        }

        async function extractThumbs(asset, entry) {
            if (!video) { video = document.createElement('video'); video.muted = true; video.playsInline = true; video.preload = 'auto'; }
            const el = video;
            try {
                el.src = asset.media_url;
                el.load();
                await once(el, 'loadeddata', 20000);
                const vw = el.videoWidth || asset.width || 16, vh = el.videoHeight || asset.height || 9;
                const canvas = document.createElement('canvas');
                canvas.width = THUMB_WIDTH; canvas.height = Math.max(1, Math.round(THUMB_WIDTH * vh / vw));
                const ctx = canvas.getContext('2d');
                for (const frame of thumbnailTimes(asset.duration_frames, THUMB_COUNT)) {
                    if (disposed) return;
                    el.currentTime = frame / FPS;
                    await once(el, 'seeked', 10000);
                    ctx.drawImage(el, 0, 0, canvas.width, canvas.height);
                    const url = await canvasURL(canvas);
                    if (!url) return;
                    entry.list.push({ frame, url });
                    if (entry.list.length === 1) notify(asset.id);
                }
                entry.state = 'ready';
            } finally {
                try { el.removeAttribute('src'); el.load(); } catch (_) { /* element already released */ }
            }
        }

        async function decodePeaks(asset, entry) {
            const response = await fetch(asset.media_url, { credentials: 'same-origin', signal: abort.signal });
            const length = Number(response.headers.get('content-length') || 0);
            if (!response.ok || length > MAX_PEAK_BYTES) throw new Error('waveform_unavailable');
            const buffer = await response.arrayBuffer();
            if (disposed || buffer.byteLength > MAX_PEAK_BYTES) throw new Error('waveform_unavailable');
            const Offline = window.OfflineAudioContext || window.webkitOfflineAudioContext;
            if (!Offline) throw new Error('waveform_unavailable');
            const audio = await new Offline(1, 1, 8000).decodeAudioData(buffer);
            const channels = [];
            for (let c = 0; c < Math.min(2, audio.numberOfChannels); c++) channels.push(audio.getChannelData(c));
            const data = peaksFromChannels(channels, audio.sampleRate, 50, 6000);
            entry.data = { peaks: data, perFrame: data.length / Math.max(1 / FPS, audio.duration) / FPS };
            entry.state = 'ready';
        }

        async function pump() {
            if (running || disposed) return;
            running = true;
            while (queue.length && !disposed) {
                const job = queue.shift();
                try {
                    if (job.type === 'thumbs') await extractThumbs(job.asset, job.entry);
                    else await decodePeaks(job.asset, job.entry);
                } catch (_) {
                    job.entry.state = 'failed';
                }
                notify(job.asset.id);
            }
            running = false;
        }

        function thumbsFor(asset) {
            if (!asset || !asset.id || !asset.media_url) return [];
            if (asset.kind === 'image') return [{ frame: 0, url: asset.media_url }];
            if (asset.kind !== 'video') return [];
            let entry = thumbs.get(asset.id);
            if (!entry) {
                entry = { state: 'pending', list: [] };
                thumbs.set(asset.id, entry);
                queue.unshift({ type: 'thumbs', asset, entry });
                pump();
            }
            return entry.list;
        }

        function poster(asset) {
            const list = thumbsFor(asset);
            return list.length ? list[0].url : '';
        }

        function peaksFor(asset) {
            if (!hasWaveform(asset) || !asset.media_url) return null;
            let entry = peaks.get(asset.id);
            if (!entry) {
                entry = { state: 'pending', data: null };
                peaks.set(asset.id, entry);
                queue.push({ type: 'peaks', asset, entry });
                pump();
            }
            return entry.data;
        }

        function dispose() {
            if (disposed) return;
            disposed = true;
            abort.abort();
            queue.length = 0;
            if (video) { try { video.removeAttribute('src'); video.load(); } catch (_) { /* released */ } video = null; }
            urls.forEach(url => URL.revokeObjectURL(url));
            urls.clear(); thumbs.clear(); peaks.clear();
        }

        return { thumbs: thumbsFor, poster, peaks: peaksFor, dispose };
    }

    window.VideoStudioMedia = { create, thumbnailTimes, peaksFromChannels, pickThumb, isArtwork, hasWaveform };
})();
