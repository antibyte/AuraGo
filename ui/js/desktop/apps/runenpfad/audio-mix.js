    const TRIM_MIN_DB = -14;
    const TRIM_MAX_DB = 24;
    const FAR_FACTOR = 1.2;
    const FAR_GAIN = 0.3;
    const BUS = { music: 0.62, master: 0.92, limiterThreshold: -4, limiterRatio: 20, limiterAttack: 0.001, limiterRelease: 0.06, outGain: 0.80 };
    const ROOM_TONES = {
        wood: { primary: 'fire', secondary: '', level: 0.5 },
        cave: { primary: 'space-hum', secondary: 'rain-light', level: 0.7 },
        tomb: { primary: 'space-hum', secondary: 'rain-light', level: 0.7 },
        ice: { primary: 'space-hum', secondary: 'rain-light', level: 0.7 },
        works: { primary: 'industrial', secondary: 'engine', level: 0.6 }
    };

    // Linear gain for a cue: looks up type:variant, then type, else 1. Clamped to -14 ... +24 dB.
    function trimFor(type, variant) {
        let db;
        if (variant !== undefined && variant !== null && Object.prototype.hasOwnProperty.call(TRIM, type + ':' + variant)) db = TRIM[type + ':' + variant];
        else if (Object.prototype.hasOwnProperty.call(TRIM, type)) db = TRIM[type];
        if (typeof db !== 'number' || !isFinite(db)) return 1;
        return Math.pow(10, Math.max(TRIM_MIN_DB, Math.min(TRIM_MAX_DB, db)) / 20);
    }

    // 1 inside the view, falling linearly to 0.3 at 1.2 view widths beyond the edge.
    function distanceGain(x, camera) {
        if (typeof x !== 'number' || !isFinite(x) || !camera || !(camera.w > 0)) return 1;
        const left = camera.x;
        const right = camera.x + camera.w;
        const out = x < left ? left - x : (x > right ? x - right : 0);
        if (out <= 0) return 1;
        return 1 - (1 - FAR_GAIN) * Math.min(1, out / (camera.w * FAR_FACTOR));
    }

    // Ambience spec to pass as worldAmbience: a room tone inside an interior, else the stage ambience unchanged.
    function ambienceFor(sim) {
        const room = sim && sim.interior && sim.interior.room;
        const theme = room && room.def && room.def.theme;
        if (theme && ROOM_TONES[theme]) return Object.assign({}, ROOM_TONES[theme]);
        return sim && sim.stage ? sim.stage.ambience : undefined;
    }

    root.RunenpfadAudioMix = { TRIM: TRIM, BUS: BUS, ROOM_TONES: ROOM_TONES, trimFor: trimFor, distanceGain: distanceGain, ambienceFor: ambienceFor };
